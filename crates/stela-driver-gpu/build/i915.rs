/// The unit of i915's own `module_init`.
const INITCALLS: UnitSpec = UnitSpec {
    scope: stela_c_build::linux_capture::Scope {
        slice: "gpu",
        group: "i915",
        group_ordinal: 8,
        unit_ordinal: 1,
        global_ordinal: 8,
    },
    source: "drivers/gpu/drm/i915/i915_module",
    module: MODULE.name,
    file: MODULE.file,
};

pub fn port(linux: &mut Linux) {
    println!("cargo:rerun-if-changed={I915}");
    println!("cargo:rerun-if-changed=src/compat/i915");
    let sources = OBJECTS
        .iter()
        .map(|object| Path::new(I915).join(format!("{object}.c")))
        .chain([PathBuf::from("src/compat/i915/intel_display_params.c")])
        .collect::<Vec<PathBuf>>();
    port::build(
        linux,
        &Port {
            module: MODULE,
            // i915's Makefile: `-I$(src)` and `-DI915` for every object.
            includes: &["i915"],
            defines: &["I915"],
            initcalls: INITCALLS,
            image: "stela_linux_i915_image",
            archive: "stela-i915",
            open: OPEN,
        },
        &sources,
    );
}
